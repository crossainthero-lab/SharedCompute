"""Minimal CUDA driver API binding (ctypes).

Needs only the NVIDIA driver's libcuda, not the CUDA toolkit or PyTorch. Kernels ship as PTX
(kernels/*.ptx, generated by agent/kernels/build_ptx.py) and are JIT-compiled by the driver for the
installed GPU, so one file serves Kepler (sm_30) through current GPUs.

Driver API versions are integers: 5050 = CUDA 5.5, 12020 = CUDA 12.2.
"""
from __future__ import annotations

import ctypes
import os
import sys
from contextlib import contextmanager
from ctypes import byref, c_char_p, c_float, c_int, c_int32, c_size_t, c_uint, c_uint64, c_void_p
from pathlib import Path
from typing import Callable, List, Tuple

from .errors import Cancelled, Incompatible

MIB = 1024 * 1024
KERNEL_DIR = Path(__file__).resolve().parent / "kernels"
MATMUL_PTX = KERNEL_DIR / "matmul_i32.ptx"

CU_DEVICE_ATTRIBUTE_COMPUTE_CAPABILITY_MAJOR = 75
CU_DEVICE_ATTRIBUTE_COMPUTE_CAPABILITY_MINOR = 76
CU_JIT_ERROR_LOG_BUFFER = 5
CU_JIT_ERROR_LOG_BUFFER_SIZE_BYTES = 6
JIT_LOG_BYTES = 8192
BLOCK = 16


class CudaUnavailable(Exception):
    """No usable CUDA driver on this machine."""


class CudaError(Exception):
    def __init__(self, call: str, code: int, name: str, detail: str = ""):
        super().__init__(f"{call} failed: {name}" + (f" ({detail.strip()})" if detail.strip() else ""))
        self.call, self.code, self.name, self.detail = call, code, name, detail


def load_library():
    if sys.platform.startswith("linux"):
        candidates = ["libcuda.so.1", "libcuda.so"]
    elif sys.platform == "win32":
        candidates = ["nvcuda.dll"]
    else:
        raise CudaUnavailable(f"CUDA is not available on {sys.platform}")
    for name in candidates:
        try:
            return ctypes.CDLL(name)
        except OSError:
            continue
    raise CudaUnavailable("libcuda not found; is the NVIDIA driver installed?")


class Driver:
    """Thin wrapper; `lib` can be any object exposing the cu* functions (tests pass a fake)."""

    def __init__(self, lib=None):
        # Match nvidia-smi / NVML ordering. Devices are also matched by PCI bus id, not index alone.
        os.environ.setdefault("CUDA_DEVICE_ORDER", "PCI_BUS_ID")
        self.lib = lib if lib is not None else load_library()
        self._initialized = False

    # -- plumbing --------------------------------------------------------------------------

    def _symbol(self, names: Tuple[str, ...]):
        for name in names:
            fn = getattr(self.lib, name, None)
            if fn is not None:
                return name, fn
        raise CudaError(names[0], -1, "symbol missing; the driver is too old")

    def call(self, names, *args) -> None:
        name, fn = self._symbol((names,) if isinstance(names, str) else tuple(names))
        rc = fn(*args)
        if rc != 0:
            raise CudaError(name, rc, self.error_name(rc))

    def _quiet(self, names, *args) -> None:
        try:
            self.call(names, *args)
        except CudaError:
            pass  # cleanup paths must not mask the original error

    def error_name(self, rc: int) -> str:
        fn = getattr(self.lib, "cuGetErrorName", None)
        if fn is not None:
            text = c_char_p()
            if fn(rc, byref(text)) == 0 and text.value:
                return text.value.decode(errors="replace")
        return f"CUDA error {rc}"

    # -- discovery -------------------------------------------------------------------------

    def init(self) -> None:
        if not self._initialized:
            self.call("cuInit", c_uint(0))
            self._initialized = True

    def driver_version(self) -> int:
        version = c_int()
        self.call("cuDriverGetVersion", byref(version))
        return version.value

    def device_count(self) -> int:
        self.init()
        count = c_int()
        self.call("cuDeviceGetCount", byref(count))
        return count.value

    def device(self, ordinal: int) -> c_int:
        self.init()
        dev = c_int()
        self.call("cuDeviceGet", byref(dev), c_int(ordinal))
        return dev

    def name(self, dev: c_int) -> str:
        buf = ctypes.create_string_buffer(256)
        self.call("cuDeviceGetName", buf, c_int(256), dev)
        return buf.value.decode(errors="replace")

    def compute_capability(self, dev: c_int) -> str:
        major, minor = c_int(), c_int()
        self.call("cuDeviceGetAttribute", byref(major), c_int(CU_DEVICE_ATTRIBUTE_COMPUTE_CAPABILITY_MAJOR), dev)
        self.call("cuDeviceGetAttribute", byref(minor), c_int(CU_DEVICE_ATTRIBUTE_COMPUTE_CAPABILITY_MINOR), dev)
        return f"{major.value}.{minor.value}"

    def total_mem_mb(self, dev: c_int) -> int:
        total = c_size_t()
        self.call(("cuDeviceTotalMem_v2", "cuDeviceTotalMem"), byref(total), dev)
        return total.value // MIB

    def pci_bus_id(self, dev: c_int) -> str:
        buf = ctypes.create_string_buffer(32)
        self.call("cuDeviceGetPCIBusId", buf, c_int(32), dev)
        return buf.value.decode()

    # -- execution -------------------------------------------------------------------------

    @contextmanager
    def context(self, dev: c_int):
        ctx = c_void_p()
        self.call(("cuCtxCreate_v2", "cuCtxCreate"), byref(ctx), c_uint(0), dev)
        try:
            yield ctx
        finally:
            self._quiet(("cuCtxDestroy_v2", "cuCtxDestroy"), ctx)

    def mem_info_mb(self) -> Tuple[int, int]:
        free, total = c_size_t(), c_size_t()
        self.call(("cuMemGetInfo_v2", "cuMemGetInfo"), byref(free), byref(total))
        return free.value // MIB, total.value // MIB

    def load_module(self, ptx: bytes) -> c_void_p:
        module = c_void_p()
        log = ctypes.create_string_buffer(JIT_LOG_BYTES)
        options = (c_int * 2)(CU_JIT_ERROR_LOG_BUFFER, CU_JIT_ERROR_LOG_BUFFER_SIZE_BYTES)
        values = (c_void_p * 2)(ctypes.addressof(log), JIT_LOG_BYTES)
        try:
            self.call("cuModuleLoadDataEx", byref(module), c_char_p(ptx), c_uint(2), options, values)
        except CudaError as exc:
            raise CudaError(exc.call, exc.code, exc.name, log.value.decode(errors="replace")) from None
        return module

    def function(self, module: c_void_p, name: str) -> c_void_p:
        fn = c_void_p()
        self.call("cuModuleGetFunction", byref(fn), module, name.encode())
        return fn

    def alloc(self, nbytes: int) -> c_uint64:
        ptr = c_uint64()
        self.call(("cuMemAlloc_v2", "cuMemAlloc"), byref(ptr), c_size_t(nbytes))
        return ptr

    def free(self, ptr: c_uint64) -> None:
        self._quiet(("cuMemFree_v2", "cuMemFree"), ptr)

    def htod(self, dst: c_uint64, src, nbytes: int) -> None:
        self.call(("cuMemcpyHtoD_v2", "cuMemcpyHtoD"), dst, src, c_size_t(nbytes))

    def dtoh(self, dst, src: c_uint64, nbytes: int) -> None:
        self.call(("cuMemcpyDtoH_v2", "cuMemcpyDtoH"), dst, src, c_size_t(nbytes))

    def launch(self, fn: c_void_p, grid: Tuple[int, int], block: Tuple[int, int], args: list) -> None:
        # cuLaunchKernel takes an array of pointers to each argument value.
        params = (c_void_p * len(args))(*[ctypes.addressof(a) for a in args])
        self.call("cuLaunchKernel", fn, c_uint(grid[0]), c_uint(grid[1]), c_uint(1),
                  c_uint(block[0]), c_uint(block[1]), c_uint(1), c_uint(0), c_void_p(None), params, c_void_p(None))

    def synchronize(self) -> None:
        self.call("cuCtxSynchronize")

    def event(self) -> c_void_p:
        ev = c_void_p()
        self.call("cuEventCreate", byref(ev), c_uint(0))
        return ev

    def record(self, ev: c_void_p) -> None:
        self.call("cuEventRecord", ev, c_void_p(None))

    def elapsed_ms(self, start: c_void_p, stop: c_void_p) -> float:
        self.call("cuEventSynchronize", stop)
        ms = c_float()
        self.call("cuEventElapsedTime", byref(ms), start, stop)
        return ms.value

    def destroy_event(self, ev: c_void_p) -> None:
        self._quiet(("cuEventDestroy_v2", "cuEventDestroy"), ev)


def probe(driver_factory: Callable[[], Driver] = Driver) -> dict:
    """What the CUDA driver says about this machine. Never raises."""
    result = {"available": False, "error": None, "driver_version": None, "devices": []}
    try:
        driver = driver_factory()
        driver.init()
        result["driver_version"] = driver.driver_version()
        for ordinal in range(driver.device_count()):
            dev = driver.device(ordinal)
            result["devices"].append({
                "ordinal": ordinal, "name": driver.name(dev), "compute_capability": driver.compute_capability(dev),
                "total_mb": driver.total_mem_mb(dev), "pci_bus_id": driver.pci_bus_id(dev),
            })
        result["available"] = True
    except (CudaUnavailable, CudaError) as exc:
        result["error"] = str(exc)
    return result


def run_matmul_i32(driver: Driver, ordinal: int, a_vals: List[int], b_vals: List[int], n: int, repeats: int,
                   should_stop: Callable[[], bool]) -> Tuple[List[int], float]:
    """C = A x B on the GPU. Returns C (row-major) and the mean kernel time in milliseconds."""
    ptx = MATMUL_PTX.read_bytes() + b"\0"
    nbytes = n * n * 4
    dev = driver.device(ordinal)
    with driver.context(dev):
        free_mb, _total = driver.mem_info_mb()
        need_mb = (3 * nbytes) // MIB + 16
        if free_mb < need_mb:
            raise Incompatible(f"only {free_mb} MB of VRAM free; this job needs about {need_mb} MB")
        module = driver.load_module(ptx)
        buffers, events = [], []
        try:
            fn = driver.function(module, "matmul_i32")
            host_a = (c_int32 * (n * n))(*a_vals)
            host_b = (c_int32 * (n * n))(*b_vals)
            host_c = (c_int32 * (n * n))()
            for _ in range(3):
                buffers.append(driver.alloc(nbytes))  # appended one by one so a failure frees the rest
            d_a, d_b, d_c = buffers
            driver.htod(d_a, host_a, nbytes)
            driver.htod(d_b, host_b, nbytes)
            args = [d_a, d_b, d_c, c_int32(n)]
            grid = ((n + BLOCK - 1) // BLOCK, (n + BLOCK - 1) // BLOCK)
            driver.launch(fn, grid, (BLOCK, BLOCK), args)  # warm-up (includes lazy JIT work)
            driver.synchronize()
            start, stop = driver.event(), driver.event()
            events += [start, stop]
            driver.record(start)
            for _ in range(repeats):
                if should_stop():
                    raise Cancelled()
                driver.launch(fn, grid, (BLOCK, BLOCK), args)
            driver.record(stop)
            kernel_ms = driver.elapsed_ms(start, stop) / max(1, repeats)
            driver.synchronize()
            driver.dtoh(host_c, d_c, nbytes)
            return list(host_c), kernel_ms
        finally:
            for ev in events:
                driver.destroy_event(ev)
            for buf in buffers:
                driver.free(buf)
            driver._quiet("cuModuleUnload", module)
